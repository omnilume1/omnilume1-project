import { swPushPlan } from './sw-push';

// The service worker's rules. public/sw.js is generated from this file
// (scripts/write-sw.mjs) and a unit test fails when it is stale, so the worker
// that ships is exactly what is tested here.

export type SwCacheDecision = 'static' | 'navigate' | 'bypass';

export interface SwRequestFacts {
  method: string;
  url: string;
  /** `Request.mode`: a page load is 'navigate'. */
  mode: string;
  hasAuthorization: boolean;
  hasRange: boolean;
}

export const SW_STATIC_CACHE = 'omnilume-static-v1';
export const SW_OFFLINE_CACHE = 'omnilume-offline-v1';
export const SW_OFFLINE_URL = '/offline.html';
/** The only thing stored at install time. */
export const SW_PRECACHE_URLS = [SW_OFFLINE_URL];
/** About three deploys of build files; the oldest are dropped first. */
export const SW_STATIC_MAX_ENTRIES = 300;

/** Only this decision ever writes to a cache. */
export const swDecisionStores = (decision: SwCacheDecision) => decision === 'static';

/**
 * What the worker does with a request.
 * - 'static': a hashed, immutable build file. Cache first.
 * - 'navigate': a page load. Network first; the precached offline page when the
 *   network fails. The page itself is never stored.
 * - 'bypass': the worker does not touch it.
 * Privacy rule: nothing but build files is stored, so no page, API reply, auth
 * exchange, Supabase or R2 response, media range or write can end up in a cache.
 *
 * Self-contained on purpose (no imports, no outer variables): its source is
 * copied into public/sw.js.
 */
export function swCachePolicy(request: SwRequestFacts, origin: string): SwCacheDecision {
  if (request.method !== 'GET' || request.hasAuthorization || request.hasRange) return 'bypass';
  let url: URL;
  try {
    url = new URL(request.url);
  } catch {
    return 'bypass';
  }
  if (url.origin !== origin) return 'bypass';
  if (request.mode === 'navigate') return 'navigate';
  if (url.pathname.startsWith('/_next/static/')) return 'static';
  return 'bypass';
}

/** The full text of public/sw.js. */
export function renderServiceWorker(): string {
  return `// Generated by scripts/write-sw.mjs from src/lib/sw-cache-policy.ts. Do not edit by hand.
const STATIC_CACHE = ${JSON.stringify(SW_STATIC_CACHE)};
const OFFLINE_CACHE = ${JSON.stringify(SW_OFFLINE_CACHE)};
const OFFLINE_URL = ${JSON.stringify(SW_OFFLINE_URL)};
const STATIC_MAX_ENTRIES = ${SW_STATIC_MAX_ENTRIES};

${swCachePolicy.toString()}

self.addEventListener('install', (event) => {
  // 'reload' skips the browser's HTTP cache, so an old offline page is never pinned.
  event.waitUntil(
    caches.open(OFFLINE_CACHE)
      .then((cache) => cache.add(new Request(OFFLINE_URL, { cache: 'reload' })))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name !== STATIC_CACHE && name !== OFFLINE_CACHE).map((name) => caches.delete(name)));
    // The page request starts while the worker boots, so a cold start costs nothing.
    if (self.registration.navigationPreload) await self.registration.navigationPreload.enable();
    await self.clients.claim();
  })());
});

async function trimStaticCache(cache) {
  const keys = await cache.keys();
  for (const key of keys.slice(0, Math.max(0, keys.length - STATIC_MAX_ENTRIES))) await cache.delete(key);
}

async function staticFile(event) {
  const cache = await caches.open(STATIC_CACHE);
  const cached = await cache.match(event.request);
  if (cached) return cached;
  const response = await fetch(event.request);
  // Only complete, same-origin files are kept. Their names are content hashes, so they never go stale.
  if (response.status === 200 && response.type === 'basic') {
    const copy = response.clone();
    event.waitUntil(cache.put(event.request, copy).then(() => trimStaticCache(cache)).catch(() => undefined));
  }
  return response;
}

async function pageOrOffline(event) {
  try {
    const preloaded = await event.preloadResponse;
    return preloaded || await fetch(event.request);
  } catch {
    const offline = await caches.match(OFFLINE_URL);
    return offline || Response.error();
  }
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const decision = swCachePolicy({
    method: request.method,
    url: request.url,
    mode: request.mode,
    hasAuthorization: request.headers.has('authorization'),
    hasRange: request.headers.has('range'),
  }, self.location.origin);
  if (decision === 'static') event.respondWith(staticFile(event));
  else if (decision === 'navigate') event.respondWith(pageOrOffline(event));
});

// Push notifications. The payload never carries message text (see src/lib/push-payload.ts).
${swPushPlan.toString()}

self.addEventListener('push', (event) => {
  event.waitUntil((async () => {
    let payload = null;
    try {
      payload = event.data ? event.data.json() : null;
    } catch {
      payload = null;
    }
    const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    const focused = windows.filter((client) => client.focused && client.visibilityState === 'visible').map((client) => client.url);
    const tag = payload && typeof payload.tag === 'string' ? payload.tag : '';
    const showing = tag ? await self.registration.getNotifications({ tag }) : [];
    const existing = showing.length ? Number((showing[0].data && showing[0].data.count) || 1) : 0;
    const plan = swPushPlan(payload, self.location.origin, focused, existing);
    if (plan) await self.registration.showNotification(plan.title, plan.options);
  })());
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const data = event.notification.data;
  event.waitUntil((async () => {
    let target;
    try {
      target = new URL(data && typeof data.url === 'string' ? data.url : '/home', self.location.origin);
    } catch {
      return;
    }
    // Only this site is ever opened by a tap.
    if (target.origin !== self.location.origin) return;
    const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    for (const client of windows) {
      try {
        await client.focus();
        await client.navigate(target.href);
        return;
      } catch {
        // That window cannot be reused: try the next one, then open a new one.
      }
    }
    await self.clients.openWindow(target.href);
  })());
});
`;
}
